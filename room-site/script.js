const languageButtons = document.querySelectorAll("[data-language]");
const defaultLanguage = "en";
const defaultText = new Map(
  [...document.querySelectorAll("[data-i18n]")].map((element) => [element, element.innerHTML])
);
const defaultPlaceholders = new Map(
  [...document.querySelectorAll("[data-i18n-placeholder]")].map((element) => [element, element.placeholder])
);

function setLanguage(language) {
  const dictionary = language === defaultLanguage ? null : translations[language];
  if (language !== defaultLanguage && !dictionary) return;

  document.documentElement.lang = language === "sw" ? "sw" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.innerHTML = dictionary ? dictionary[key] || defaultText.get(element) : defaultText.get(element);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    element.placeholder = dictionary ? dictionary[key] || defaultPlaceholders.get(element) : defaultPlaceholders.get(element);
  });
  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.language);
  });
});

const menuToggle = document.querySelector(".menu-toggle");
const primaryNav = document.querySelector("#primary-nav");

menuToggle.addEventListener("click", () => {
  const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isExpanded));
  primaryNav.classList.toggle("is-open", !isExpanded);
});

primaryNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    menuToggle.setAttribute("aria-expanded", "false");
    primaryNav.classList.remove("is-open");
  });
});

const checkin = document.querySelector('input[name="checkin"]');
const checkout = document.querySelector('input[name="checkout"]');
const today = new Date();
const localToday = new Date(today.getTime() - today.getTimezoneOffset() * 60000)
  .toISOString()
  .slice(0, 10);
checkin.min = localToday;
checkout.min = localToday;

checkin.addEventListener("change", () => {
  checkout.min = checkin.value || localToday;
  if (checkout.value && checkout.value <= checkin.value) checkout.value = "";
});

const bookingForm = document.querySelector("#booking-form");
const formError = document.querySelector("#form-error");

bookingForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const formData = new FormData(bookingForm);
  const language = document.documentElement.lang;
  const swahili = language === "sw";
  const startDate = formData.get("checkin");
  const endDate = formData.get("checkout");

  if (endDate <= startDate) {
    formError.textContent = swahili
      ? translations.sw.errorDates
      : "Check-out must be after check-in.";
    formError.hidden = false;
    checkout.focus();
    return;
  }

  formError.hidden = true;
  const message = swahili
    ? [
        "Habari Family Corner BNB, naomba kuulizia ukaaji.",
        `Jina: ${formData.get("name")}`,
        `Kuingia: ${startDate}`,
        `Kutoka: ${endDate}`,
        `Wageni: ${formData.get("guests")}`,
        formData.get("message") ? `Ujumbe: ${formData.get("message")}` : ""
      ].filter(Boolean).join("\n")
    : [
        "Hello Family Corner BNB, I'd like to enquire about a stay.",
        `Name: ${formData.get("name")}`,
        `Check-in: ${startDate}`,
        `Check-out: ${endDate}`,
        `Guests: ${formData.get("guests")}`,
        formData.get("message") ? `Note: ${formData.get("message")}` : ""
      ].filter(Boolean).join("\n");

  window.open(`https://wa.me/255793950555?text=${encodeURIComponent(message)}`, "_blank", "noopener,noreferrer");
});

